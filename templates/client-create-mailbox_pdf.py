W = A4[0] - 40 * mm  # content width


def P(text, st="body"):
    return Paragraph(text, S[st])


def code(t):
    return f'<font name="Mono" size="9.5" color="#B03A2E">{t}</font>'


def steps(items):
    """Numbered steps as a two-column table (number badge + text)."""
    rows = [[Paragraph(f'<font color="white"><b>{i}</b></font>', ParagraphStyle("n", **{**base, "alignment": 1, "fontSize": 9.5, "leading": 12})),
             P(t, "step")] for i, t in enumerate(items, 1)]
    t = Table(rows, colWidths=[8 * mm, W - 8 * mm])
    cmds = [
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (1, 0), (1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]
    for r in range(len(rows)):
        cmds.append(("BACKGROUND", (0, r), (0, r), ACCENT))
    t.setStyle(TableStyle(cmds))
    return KeepTogether([t])


def box(text, kind="tip"):
    bg, line, label = (TIP_BG, ACCENT, "Совет") if kind == "tip" else (WARN_BG, WARN_LINE, "Важно")
    t = Table([[P(f"<b>{label}.</b> {text}", "box")]], colWidths=[W])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), bg),
        ("LINEBEFORE", (0, 0), (0, -1), 3, line),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ("TOPPADDING", (0, 0), (-1, -1), 7),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
    ]))
    return t


def table(header, rows, widths):
    data = [[P(h, "cellb") for h in header]] + [[P(c, "cell") for c in r] for r in rows]
    t = Table(data, colWidths=[w * W for w in widths], repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), HEAD_BG),
        ("GRID", (0, 0), (-1, -1), 0.5, GRID),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
    ]))
    return t


def on_page(c, doc):
    c.saveState()
    c.setStrokeColor(GRID)
    c.line(20 * mm, 15 * mm, A4[0] - 20 * mm, 15 * mm)
    c.setFont("Sans", 8.5)
    c.setFillColor(MUTED)
    c.drawString(20 * mm, 10 * mm, "Инструкция: как создать почтовый ящик")
    c.drawRightString(A4[0] - 20 * mm, 10 * mm, f"стр. {doc.page}")
    c.restoreState()


